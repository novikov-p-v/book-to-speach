"""Turn find_wrong.py output into espeak "word $N" entries (dictsource/ru_extra).

usage: make_extra.py <wrong.tsv> <ruaccent dir> <out ru_extra>

Kept: words where espeak puts the stress on a *different* vowel than RUAccent. Dropped:
- words espeak leaves unstressed on purpose (было, может, перед ... in connected speech),
- ё-homographs (RUAccent yo_homographs) and words with a ё-twin in the dictionary
  (жены = жены́ / жёны: books are printed without ё, so the spelling is ambiguous),
- stress beyond the 7th vowel (espeak only supports $1..$7),
- clitics that are unstressed after a hyphen in RUAccent's own entries (всё-таки -> таки, кто-либо -> либо).
"""
import gzip, json, sys

wrong, ra, out = sys.argv[1:4]
acc = json.load(gzip.open(f"{ra}/accents.json.gz", "rt", encoding="utf-8"))
yo_homographs = json.load(gzip.open(f"{ra}/yo_homographs.json.gz", "rt", encoding="utf-8"))


# parts written after a hyphen without stress in compounds: "все-таки" -> "вс+е-таки" makes "таки" a clitic
clitics = set()
for k, v in acc.items():
    if "-" in k:
        for part in v.split("-")[1:]:
            if "+" not in part:
                clitics.add(part)


def has_yo_twin(w):
    return any(w[:i] + "ё" + w[i + 1:] in acc for i, c in enumerate(w) if c == "е")


n_in = n_out = 0
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/ru-stress/make_extra.py from RUAccent (MIT). Do not edit.\n")
    for line in open(wrong, encoding="utf-8"):
        n_in += 1
        word, vowel, espeak = line.rstrip("\n").split("\t")
        if espeak == "None" or word in yo_homographs or word in clitics or int(vowel) > 7 or has_yo_twin(word):
            continue
        f.write(f"{word} ${vowel}\n")
        n_out += 1
print(f"{n_in} differing words -> {n_out} entries in {out}")
